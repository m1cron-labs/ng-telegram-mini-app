export enum BottomButtonPosition {
  /**
   * Displayed to the left of the main button.
   */
  LEFT = 'left',

  /**
   * Displayed to the right of the main button.
   */
  RIGHT = 'right',

  /**
   * Displayed above the main button.
   */
  TOP = 'top',

  /**
   * Displayed below the main button.
   */
  BOTTOM = 'bottom',
}
